public class Apartado030103 {

    public void ejercicio01() {
        double raiz = Math.sqrt(256);
        System.out.println("Raíz cuadrada de 256: " + raiz);
    }

    public void ejercicio02() {
        double cubo = Math.pow(9, 3);
        System.out.println("9 elevado al cubo: " + cubo);
    }

    public void ejercicio03() {
        double aleatorio = (Math.random() * (10 - 5)) + 5;
        System.out.println("Número aleatorio entre 5 y 10: " + aleatorio);
    }

    public void ejercicio04() {
        double radio = 10.0;
        double superficie = Math.PI * Math.pow(radio, 2);
        System.out.println("Superficie del círculo de radio 10: " + superficie);
    }
    
}